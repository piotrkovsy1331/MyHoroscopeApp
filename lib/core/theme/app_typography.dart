/// Bundled font families (SIL OFL 1.1, see assets/licenses).
abstract final class AppFonts {
  /// Elegant inscriptional capitals for titles.
  static const display = 'Cinzel';

  /// Highly legible sans-serif for body copy.
  static const body = 'Inter';

  /// Noto Sans Symbols subset that contains only the 12 zodiac glyphs, so
  /// iOS/Android never swap them for colour emoji.
  static const zodiac = 'ZodiacSymbols';
}
